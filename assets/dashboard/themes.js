/* global document, window */

const rgb = hex =>
  [1, 3, 5].map(offset => parseInt(hex.slice(offset, offset + 2), 16) / 255);

function theme(
  id,
  name,
  colorScheme,
  colors,
  sceneColors,
  {appearance = 'default', scene = 'factory'} = {},
) {
  const {
    selection = colors['selection-bg'],
    running = colors['status-running'],
    queued = colors['status-queued'],
    completed = colors['status-completed'],
    failed = colors['status-failed'],
    cancelling = colors['status-cancelling'],
    compacting = colors['status-compacting'],
    cancelled = colors['status-cancelled'],
    ...materials
  } = sceneColors;
  return Object.freeze({
    id,
    name,
    colorScheme,
    appearance,
    scene,
    colors: Object.freeze(colors),
    scenePalette: Object.freeze(
      Object.fromEntries(
        Object.entries({
          ...materials,
          selection,
          running,
          queued,
          completed,
          failed,
          cancelling,
          compacting,
          cancelled,
        }).map(([key, value]) => [
          key,
          Object.freeze(typeof value === 'string' ? rgb(value) : value),
        ]),
      ),
    ),
  });
}

